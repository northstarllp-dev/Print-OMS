/**
 * Generate .env.test from local `supabase status -o env`.
 * Local-only keys never commit .env.test.
 *
 * Usage: node scripts/generate-env-test.mjs
 */
import { execSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");

let statusEnv = "";
try {
  statusEnv = execSync("npx supabase status -o env", {
    cwd: root,
    encoding: "utf8",
    stdio: ["ignore", "pipe", "pipe"],
  });
} catch (err) {
  console.error(
    "Failed to read supabase status. Is `npx supabase start` running?\n",
    err?.stderr || err?.message
  );
  process.exit(1);
}

const parsed = Object.fromEntries(
  statusEnv
    .split(/\r?\n/)
    .map((l) => l.trim())
    .filter((l) => l && !l.startsWith("#") && l.includes("="))
    .map((l) => {
      const i = l.indexOf("=");
      return [l.slice(0, i), l.slice(i + 1).replace(/^"|"$/g, "")];
    })
);

const apiUrl =
  parsed.API_URL || parsed.SUPABASE_URL || "http://127.0.0.1:54321";
const anonKey =
  parsed.ANON_KEY ||
  parsed.PUBLISHABLE_KEY ||
  parsed.SUPABASE_ANON_KEY ||
  "";
const serviceKey =
  parsed.SERVICE_ROLE_KEY ||
  parsed.SECRET_KEY ||
  parsed.SUPABASE_SERVICE_ROLE_KEY ||
  "";

if (!anonKey || !serviceKey) {
  console.error(
    "Could not find anon/service keys in supabase status output.",
    "Keys present:",
    Object.keys(parsed).join(", ")
  );
  process.exit(1);
}

const contents = `# Generated by scripts/generate-env-test.mjs DO NOT COMMIT
# Local Supabase E2E environment for PrintOMS

CLIENT_SLUG=printoms
NEXT_PUBLIC_CLIENT_SLUG=printoms

NEXT_PUBLIC_SUPABASE_URL=${apiUrl}
NEXT_PUBLIC_SUPABASE_ANON_KEY=${anonKey}
SUPABASE_SERVICE_ROLE_KEY=${serviceKey}

# Intentionally empty token: dispatchWhatsAppNotification writes skipped outbox rows.
# Do NOT set WHATSAPP_ENABLED=false that returns before inserting the outbox row.
WHATSAPP_ACCESS_TOKEN=
WHATSAPP_PHONE_NUMBER_ID=

# Playwright
PLAYWRIGHT_ORIGIN=http://localhost:3001
`;

const outPath = resolve(root, ".env.test");
writeFileSync(outPath, contents, "utf8");
console.log(`Wrote ${outPath}`);
console.log(`API_URL=${apiUrl}`);
console.log(`ANON_KEY length=${anonKey.length}`);
console.log(`SERVICE_ROLE_KEY length=${serviceKey.length}`);
